function v = r1waw_pair_descriptor(a, b)
%R1WAW_PAIR_DESCRIPTOR  Symmetric 17-value dissimilarity of two feature vectors (e.g. HOG).
%   Order: L1(mean), L2, Linf, cosine, correlation, canberra, braycurtis, std|d|, median|d|, p90|d|,
%          |mean diff|, |std diff|, |max diff|, |energy diff|, chi2, 1-hist_inter, |sum diff|.
%   std is the population std (1/N); p90 uses linear interpolation (numpy default).
  EPS = 1e-9;
  a = double(a(:)); b = double(b(:)); d = abs(a - b);
  ac = a - mean(a); bc = b - mean(b);
  v = [mean(d), sqrt(sum(d .^ 2)), max(d), ...
       1 - (a' * b) / (norm(a) * norm(b) + EPS), ...
       1 - (ac' * bc) / (norm(ac) * norm(bc) + EPS), ...
       sum(d ./ (abs(a) + abs(b) + EPS)), ...
       sum(d) / (sum(abs(a + b)) + EPS), ...
       std(d, 1), median(d), pct_linear(d, 90), ...
       abs(mean(a) - mean(b)), abs(std(a, 1) - std(b, 1)), ...
       abs(max(a) - max(b)), abs(sum(a .^ 2) - sum(b .^ 2)), ...
       sum(d .^ 2 ./ (abs(a) + abs(b) + EPS)), ...
       1 - sum(min(abs(a), abs(b))) / (max(sum(abs(a)), sum(abs(b))) + EPS), ...
       abs(sum(a) - sum(b))];
end

function q = pct_linear(x, p)
  x = sort(x(:)); h = (numel(x) - 1) * p / 100;
  lo = floor(h); hi = min(lo + 1, numel(x) - 1);
  q = x(lo + 1) + (h - lo) * (x(hi + 1) - x(lo + 1));
end
